classdef sensor_rig_config
    % SENSOR_RIG_CONFIG
    % Defines the multi-sensor configuration for the Autonomous Vehicle:
    %   1. Forward HD Camera (Classification & Lateral Positioning)
    %   2. 360-degree 16-channel LiDAR (Free-space & 3D Clustering)
    %   3. 77 GHz Long-Range Radar (Doppler Velocity & Long-Range Detection)
    %
    % Compliant with MathWorks Automated Driving Toolbox & Lidar Toolbox.
    
    properties (Constant)
        % Ego Vehicle Dimensions (meters)
        EgoLength = 4.7;
        EgoWidth  = 1.8;
        EgoHeight = 1.4;
        
        % Sensor Indexing
        CAMERA_IDX = 1;
        RADAR_IDX  = 2;
        LIDAR_IDX  = 3;
    end
    
    methods (Static)
        function sensors = createSensorRig(egoVehicle)
            % CREATESENSORRIG Attaches Camera, Radar, and LiDAR generators to ego vehicle
            
            % 1. Forward Vision Sensor
            visionSensor = visionDetectionGenerator(...
                'SensorIndex', sensor_rig_config.CAMERA_IDX, ...
                'SensorLocation', [egoVehicle.Length/2, 0, egoVehicle.Height], ...
                'Yaw', 0, ...
                'Pitch', 0, ...
                'DetectionProbability', 0.96, ...
                'FalseAlarmRate', 1e-6, ...
                'MaxRange', 75, ...
                'FieldOfView', [65 20], ...
                'ActorProfiles', egoVehicle.Scenario.ActorProfiles);
                
            % 2. Forward Radar Sensor (Long Range, 77 GHz)
            radarSensor = drivingRadarDataGenerator(...
                'SensorIndex', sensor_rig_config.RADAR_IDX, ...
                'MountingLocation', [egoVehicle.Length/2, 0, 0.5], ...
                'FieldOfView', [90 12], ...
                'RangeLimits', [0 100], ...
                'TargetReportFormat', 'Tracks', ...
                'DetectionProbability', 0.98, ...
                'ActorProfiles', egoVehicle.Scenario.ActorProfiles);
                
            % 3. 360-degree LiDAR Sensor
            lidarSensor = lidarPointCloudGenerator(...
                'SensorIndex', sensor_rig_config.LIDAR_IDX, ...
                'SensorLocation', [0, 0, egoVehicle.Height + 0.35], ...
                'AzimuthLimits', [-180 180], ...
                'ElevationLimits', [-15 15], ...
                'RangeLimits', [0.5 80], ...
                'HasOrganizedOutput', false, ...
                'ActorProfiles', egoVehicle.Scenario.ActorProfiles);
                
            sensors = {visionSensor, radarSensor, lidarSensor};
        end
    end
end
